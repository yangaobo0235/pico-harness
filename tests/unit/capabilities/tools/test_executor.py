"""Tests for pico.capabilities.tools.executor: guardrail chain and result shape."""

from pathlib import Path

from pico.capabilities.tools.contracts import ToolResult
from pico.capabilities.tools.executor import ToolExecutor
from pico.integrations.llm.providers.fake import FakeModelClient
from pico.runtime.agent.agent import Pico
from pico.runtime.sessions.service import SessionStore
from pico.runtime.workspace.snapshot import WorkspaceContext


def _build_agent(tmp_path: Path) -> Pico:
    """Assemble an auto-approval run so the executor walks its whole guardrail chain unprompted."""
    (tmp_path / "README.md").write_text("demo\n", encoding="utf-8")
    workspace = WorkspaceContext.build(tmp_path)
    store = SessionStore(tmp_path / ".pico" / "sessions")
    return Pico(
        model_client=FakeModelClient([]),
        workspace=workspace,
        session_store=store,
        approval_policy="auto",
    )


def test_tool_executor_returns_content_and_metadata_without_side_channel(tmp_path: Path) -> None:
    """One ToolResult carries the model-facing text and the artifact-facing metadata; no side channel."""
    agent = _build_agent(tmp_path)

    result = ToolExecutor(agent).execute("read_file", {"path": "README.md", "start": 1, "end": 1})

    assert isinstance(result, ToolResult)
    assert "# README.md" in result.content
    assert result.metadata["tool_status"] == "ok"
    assert result.metadata["read_only"] is True
    assert result.metadata["workspace_changed"] is False


def test_pico_run_tool_keeps_compatibility_metadata(tmp_path: Path) -> None:
    """The facade still returns plain text while stashing the latest metadata on the instance."""
    agent = _build_agent(tmp_path)

    content = agent.run_tool("read_file", {"path": "README.md", "start": 1, "end": 1})

    assert "# README.md" in content
    assert agent._last_tool_result_metadata["tool_status"] == "ok"
