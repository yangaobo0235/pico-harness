"""Tests for pico.capabilities.tools.registry: tool binding and the per-run tool directory."""

from pathlib import Path

from pico.capabilities.tools.builtin.filesystem import read_file
from pico.capabilities.tools.builtin.spawn import delegate
from pico.capabilities.tools.contracts import ToolContext
from pico.capabilities.tools.registry import build_tool_registry


def test_tool_context_supports_file_tools_without_full_pico(tmp_path: Path) -> None:
    """File tools read workspace content from a hand-built ToolContext, with no Agent involved."""
    (tmp_path / "sample.txt").write_text("alpha\n", encoding="utf-8")
    context = ToolContext(
        root=tmp_path,
        path_resolver=lambda raw_path: (tmp_path / raw_path).resolve(),
        shell_env_provider=lambda: {"PWD": str(tmp_path)},
        depth=0,
        max_depth=1,
        spawn_delegate=lambda args: "unused",
    )

    result = read_file(context, {"path": "sample.txt", "start": 1, "end": 1})

    assert "# sample.txt" in result
    assert "alpha" in result


def test_delegate_uses_context_spawn_without_runtime_import(tmp_path: Path) -> None:
    """Delegation forwards its arguments to the injected spawn callback instead of importing runtime."""
    calls = []
    context = ToolContext(
        root=tmp_path,
        path_resolver=lambda raw_path: Path(tmp_path / raw_path),
        shell_env_provider=lambda: {"PWD": str(tmp_path)},
        depth=0,
        max_depth=1,
        spawn_delegate=lambda args: calls.append(args) or "delegate_result:\nDone",
    )

    result = delegate(context, {"task": "inspect README.md", "max_steps": 2})

    assert result == "delegate_result:\nDone"
    assert calls == [{"task": "inspect README.md", "max_steps": 2}]


def test_build_tool_registry_binds_runners_to_tool_context(tmp_path: Path) -> None:
    """Every definition is bound to this context, and delegation disappears once depth is exhausted."""
    context = ToolContext(
        root=tmp_path,
        path_resolver=lambda raw_path: Path(tmp_path / raw_path),
        shell_env_provider=lambda: {"PWD": str(tmp_path)},
        depth=1,
        max_depth=1,
        spawn_delegate=lambda args: "unused",
    )

    tools = build_tool_registry(context)

    assert "read_file" in tools
    assert "delegate" not in tools
